
CREATE TABLE IF NOT EXISTS instruments (
  id VARCHAR(100) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  full_name VARCHAR(500) NOT NULL,
  full_name_hi VARCHAR(500) DEFAULT NULL,
  category VARCHAR(255) NOT NULL,
  model VARCHAR(500) NOT NULL,
  show_in_status BOOLEAN NOT NULL DEFAULT TRUE,
  status VARCHAR(100) NOT NULL DEFAULT 'Operational',
  usage_academic VARCHAR(255) DEFAULT '',
  usage_industrial VARCHAR(255) DEFAULT '',
  usage_unit VARCHAR(255) DEFAULT '',
  features JSON NOT NULL,
  features_hi JSON DEFAULT NULL,
  applications JSON NOT NULL,
  applications_hi JSON DEFAULT NULL,
  handled_by VARCHAR(255) DEFAULT '',
  email VARCHAR(255) DEFAULT '',
  location VARCHAR(255) DEFAULT '',
  location_hi VARCHAR(255) DEFAULT NULL,
  images JSON NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS category_descriptions (
  category VARCHAR(255) PRIMARY KEY,
  description VARCHAR(500) DEFAULT '',
  description_hi VARCHAR(500) DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS events (
  id INT AUTO_INCREMENT PRIMARY KEY,
  date_label VARCHAR(255) NOT NULL,
  title VARCHAR(500) NOT NULL,
  title_hi VARCHAR(500) DEFAULT NULL,
  image VARCHAR(1000) DEFAULT '',
  full_description TEXT,
  full_description_hi TEXT DEFAULT NULL,
  venue VARCHAR(500) DEFAULT '',
  venue_hi VARCHAR(500) DEFAULT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS outreach (
  id INT AUTO_INCREMENT PRIMARY KEY,
  date_label VARCHAR(255) NOT NULL,
  title VARCHAR(500) NOT NULL,
  title_hi VARCHAR(500) DEFAULT NULL,
  image VARCHAR(1000) DEFAULT '',
  description TEXT,
  description_hi TEXT DEFAULT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
